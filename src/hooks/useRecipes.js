export function useRecipes() {
  const [recipes, setRecipes] = useState(sampleRecipes);
  const [loaded, setLoaded] = useState(false);

  useEffect(() => {
    let cancelled = false;
    fetch(import.meta.env.BASE_URL + 'recipes.json')
      .then((res) => (res.ok ? res.json() : null))
      .then((published) => {
        if (cancelled) return;
        const looksLikeRecipes = Array.isArray(published)
          && published.length > 0
          && published[0]?.id !== undefined;
        if (looksLikeRecipes) {
          setRecipes(published);
        }
      })
      .catch(() => {})
      .finally(() => {
        if (!cancelled) setLoaded(true);
      });
    return () => { cancelled = true; };
  }, []);

  useEffect(() => {
    if (!loaded) return;
    localStorage.setItem(STORAGE_KEY, JSON.stringify(recipes));
  }, [recipes, loaded]);

  const addRecipe = (recipe) => {
    const newRecipe = { ...recipe, id: Date.now().toString(), createdAt: new Date().toISOString() };
    setRecipes((prev) => [newRecipe, ...prev]);
    return newRecipe;
  };

  const updateRecipe = (id, data) => {
    setRecipes((prev) => prev.map((r) => (r.id === id ? { ...r, ...data } : r)));
  };

  const deleteRecipe = (id) => {
    setRecipes((prev) => prev.filter((r) => r.id !== id));
  };

  return { recipes, setRecipes, addRecipe, updateRecipe, deleteRecipe };
}
