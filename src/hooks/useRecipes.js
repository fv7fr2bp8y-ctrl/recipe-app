// Добавя нови sample рецепти, ако вече не съществуват (по id)
export const mergeWithSamples = (existing) => {
  const ids = new Set(existing.map((r) => r.id));
  const missing = sampleRecipes.filter((r) => !ids.has(r.id));
  return missing.length > 0 ? [...existing, ...missing] : existing;
};

export function useRecipes() {
  const [recipes, setRecipes] = useState(sampleRecipes);
  const [loaded, setLoaded] = useState(false);

  useEffect(() => {
    let cancelled = false;
    fetch(import.meta.env.BASE_URL + 'recipes.json')
      .then((res) => (res.ok ? res.json() : null))
      .then((published) => {
        if (cancelled) return;
        const looksLikeRecipes = Array.isArray(published)
          && published.length > 0
          && published[0]
          && typeof published[0].title === 'string';
        if (looksLikeRecipes) {
          setRecipes(mergeWithSamples(published));
        } else {
          try {
            const stored = localStorage.getItem(STORAGE_KEY);
            if (stored) setRecipes(mergeWithSamples(JSON.parse(stored)));
          } catch {}
        }
      })
      .catch(() => {})
      .finally(() => { if (!cancelled) setLoaded(true); });
    return () => { cancelled = true; };
  }, []);

  useEffect(() => {
    if (!loaded) return;
    localStorage.setItem(STORAGE_KEY, JSON.stringify(recipes));
  }, [recipes, loaded]);

  const addRecipe = (recipe) => {
    const newRecipe = { ...recipe, id: Date.now().toString(), createdAt: new Date().toISOString() };
    setRecipes((prev) => [newRecipe, ...prev]);
    return newRecipe;
  };

  const updateRecipe = (id, updates) => {
    setRecipes((prev) => prev.map((r) => (r.id === id ? { ...r, ...updates } : r)));
  };

  const deleteRecipe = (id) => {
    setRecipes((prev) => prev.filter((r) => r.id !== id));
  };

  return { recipes, setRecipes, addRecipe, updateRecipe, deleteRecipe };
}
